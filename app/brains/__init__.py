"""Brain implementations and the factories that build them.

The orchestrator never imports a concrete brain — it asks this package
for one by provider name. Adding an LLM-backed planner later is as
simple as registering a new entry in ``_PLANNERS`` / ``_CRITICS`` /
``_EXECUTORS``:

    from app.brains.brain_openai_planner import OpenAIPlannerBrain
    from app.llm import get_llm_client

    def _openai_planner() -> Planner:
        return OpenAIPlannerBrain(llm=get_llm_client("openai"))

    _PLANNERS["openai"] = _openai_planner

Keep provider-specific imports lazy (inside the builder function) so
optional dependencies stay optional.
"""

