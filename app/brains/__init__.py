def _agent_executor() -> Executor:
    """Autonomous agent executor — Claude with sandboxed file tools.

    Construction fails fast if ``ANTHROPIC_API_KEY`` is not set so the
    operator gets a clear error instead of a silent fallback. The agent
    is confined to ``settings.agent_workspace``; absolute paths and
    traversal segments are rejected by the sandbox before any I/O.
    """
    from app import config
    from app.agent.client import AgentClientError, AnthropicAgentClient
    from app.sandbox.fs import Sandbox

    api_key = config.settings.anthropic_api_key
    if not api_key:
        raise AgentClientError(
            "ANTHROPIC_API_KEY is not set - export it or put it in your .env file"
        )
    return AgentExecutorBrain(
        client=AnthropicAgentClient(api_key=api_key, model=config.settings.agent_model),
        sandbox=Sandbox(config.settings.agent_workspace),
    )


def _local_agent_executor() -> Executor:
    """Offline autonomous executor — pattern-matches the prompt, writes real files.

    No API key required. Useful for offline demos and to verify the agent
    loop is wired correctly without spending Anthropic credits. The
    ``LocalAgentClient`` extracts a target filename + best-effort content
    from the prompt and produces a real ``write_file`` tool call against
    the same sandbox the network agent uses.
    """
    from app import config
    from app.agent.local import LocalAgentClient
    from app.sandbox.fs import Sandbox

    return AgentExecutorBrain(
        client=LocalAgentClient(),
        sandbox=Sandbox(config.settings.agent_workspace),
    )


# Provider name → zero-arg factory. Keep factories small; put any heavy
