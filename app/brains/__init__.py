def registered_planner_providers() -> list[str]:
    """Return the names of every currently wired planner provider."""
    return sorted(_PLANNERS)


def registered_critic_providers() -> list[str]:
    """Return the names of every currently wired critic provider."""
    return sorted(_CRITICS)


def registered_executor_providers() -> list[str]:
    """Return the names of every currently wired executor provider."""
    return sorted(_EXECUTORS)


def build_planner(provider: str = "deterministic") -> Planner:
    """Instantiate a planner for the given provider name.

    Raises:
        ValueError: if the provider name is not registered.
    """
    try:
        return _PLANNERS[provider]()
    except KeyError:
        raise ValueError(
            f"unknown planner provider {provider!r}; "
            f"available: {registered_planner_providers()}"
        ) from None


