def detect_topic(prompt: str) -> str | None:
    """Return the topic key whose pattern best matches ``prompt``."""
    low = prompt.lower()
    for topic, patterns in _TOPIC_PATTERNS.items():
        for pat in patterns:
            if pat in low:
                return topic
    return None


# ── templates: (topic, ext) → content ─────────────────────────────────


def render(topic: str | None, ext: str, prompt_excerpt: str) -> str:
    """Return the template body for ``topic`` + ``ext``, with a sensible fallback."""
    key = (topic or "", ext.lower())
    if key in _TEMPLATES:
        return _TEMPLATES[key]
    # ext-only fallback (the agent at least produces a syntactically valid file).
    if ("", ext.lower()) in _TEMPLATES:
        return _TEMPLATES[("", ext.lower())].replace("{{PROMPT}}", prompt_excerpt[:80])
    # Last-resort generic.
    return f"# Auto-generated by LocalAgent\n# Prompt: {prompt_excerpt[:80]}\n"


