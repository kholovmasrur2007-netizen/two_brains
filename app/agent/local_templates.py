"""Code templates the offline LocalAgent picks from.

Each entry maps a (topic, extension) pair to a string of working code.
Templates are kept short, runnable, and self-contained — the agent
verifies many of them with a follow-up ``run_python`` call.

Topics are detected from the prompt by ``detect_topic`` which scans for
keywords in both English and Russian. If no topic matches, the generic
fallback is used.
"""

