# ── action verbs detection ────────────────────────────────────────────


_RUN_KEYWORDS  = re.compile(
    r"\b(run|execute|verify|check it works|test it works|"
    r"запусти|проверь работу|выполни)\b",
    re.IGNORECASE,
)
_LIST_KEYWORDS = re.compile(
    r"\b(list (the )?(workspace|directory|files)|"
    r"что в (рабочей )?папке|покажи файлы|show files)\b",
    re.IGNORECASE,
)
_TEST_KEYWORDS = re.compile(
    r"\b(run pytest|run the tests|запусти тесты|pytest)\b",
    re.IGNORECASE,
)


def wants_run(prompt: str) -> bool:
    return bool(_RUN_KEYWORDS.search(prompt))


def wants_list(prompt: str) -> bool:
    return bool(_LIST_KEYWORDS.search(prompt))


def wants_pytest(prompt: str) -> bool:
    return bool(_TEST_KEYWORDS.search(prompt))


# ── filename extraction ──────────────────────────────────────────────


_FILENAME_RE = re.compile(r"(?<![\w/\\])([A-Za-z0-9_-]+\.[A-Za-z0-9]{1,5})(?![\w/\\])")


def extract_filenames(prompt: str) -> list[str]:
    """Return every plausible filename mentioned in ``prompt`` (preserves order, deduped)."""
    seen: set[str] = set()
    out: list[str] = []
    for match in _FILENAME_RE.finditer(prompt):
        name = match.group(1)
        # Skip path-like tokens — sandbox would refuse them anyway.
        if "/" in name or "\\" in name or ".." in name:
            continue
        # Skip extensions that aren't useful for code generation (urls, etc.).
        if name in seen:
            continue
        seen.add(name)
        out.append(name)
    return out


# ── inline content extraction (kept compatible with old local.py) ────


_INLINE_CONTENT_RE = re.compile(
    r"(?:with\s+content|содержит|содержанием|текст(?:ом)?)\s+"
    r"(?P<q>[\"“«'])"
    r"(?P<body>.+?)"
    r"(?P=q)",
    re.IGNORECASE | re.DOTALL,
)


def extract_inline_content(prompt: str) -> str | None:
    m = _INLINE_CONTENT_RE.search(prompt)
    return m.group("body") if m else None
